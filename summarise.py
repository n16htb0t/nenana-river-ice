"""
Write down what every model is and how it scored, after all runs:

  <model folder>/model_info.txt   what the model is (method, settings, inputs), what it
                                  was trained and tested on (dates, pixels per class),
                                  and its scores with confusion matrix
  output/RESULTS.md               labelled pixels per class for every dataset and task,
                                  then every model's scores and confusion matrix, then
                                  the river/land state scores

    ~/venvs/river-ml/bin/python ~/Desktop/nenana_crops/daksh/summarise.py
"""

import re
import numpy as np
import data as D

TASKS = ["four", "snow", "river", "combined", "ind_river", "ind_ice", "ind_snow", "ind_land"]
TASK_TITLES = {"four": "Four classes (river, ice, snow, land)",
               "snow": "Binary: snow vs no snow (snow = ice + snow)",
               "river": "Binary: river vs not river (river = open water + ice)",
               "combined": "Binary snow + river merged back to four classes",
               "ind_river": "One vs rest: river", "ind_ice": "One vs rest: ice",
               "ind_snow": "One vs rest: snow", "ind_land": "One vs rest: land"}
DATASET_TITLES = {"exclude_daksh": "1. exclude_daksh: trained and cross-validated on the 4 patch dates",
                  "with_daksh": "2. with_daksh: trained and cross-validated on the 4 patch dates + daksh 2024-03-12",
                  "external_daksh": "3. external_test_daksh: trained on the 4 patch dates, tested on daksh 2024-03-12"}
MODEL_TEXT = {
    "rf": ["Random Forest (scikit-learn 1.9)",
           "300 trees, minimum 2 samples per leaf, class weights balanced per tree",
           "(balanced_subsample). Each pixel is classified on its own inputs, no neighbourhood."],
    "unetpp": ["UNet++ (segmentation-models-pytorch 0.6, PyTorch 2.14, RTX 3080)",
               "ResNet-34 encoder with ImageNet weights, 1,500 steps of 8 random 256 x 256 crops",
               "centred near labelled pixels, random 90-degree turns and flips, cross-entropy",
               "weighted by 1/sqrt(class frequency) on labelled pixels only, AdamW lr 1e-3 with",
               "one-cycle schedule, mixed precision. Sees the neighbourhood (shape, texture).",
               "Weights + input scaling: unetpp_final.pt."],
}


def label_counts(dataset):
    """{date: hand-class counts (river, ice, snow, land)} and {date: group}."""
    D.configure("four", dataset)
    counts, groups = {}, {}
    for s in D.load_all():
        y = s["y"][s["y"] != D.IGNORE]
        if len(y):
            counts[s["date"]] = np.bincount(y, minlength=4)
            groups[s["date"]] = s["group"]
    return counts, groups


def task_counts(task, hand):
    """Hand-class counts (river, ice, snow, land) -> counts of the task's classes."""
    classes, mapping, _ = D.TASKS["four" if task == "combined" else task]
    out = np.zeros(len(classes), int)
    for hid, n in zip((1, 2, 3, 4), hand):
        out[mapping[hid] - 1] += n
    return dict(zip(classes.values(), out))


def table(rows, header):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def first_block(path):
    """All-dates block of a metrics.txt (title, class table, totals, confusion)."""
    return path.read_text().split("\n\n--- ")[0].split("\n\nsettings:")[0].split("\n\ninput importance")[0].strip()


def main():
    md = ["# Results: all models, all datasets", "",
          "Generated by `summarise.py` from the `metrics.txt` files. Scores for 1 and 2 are",
          "5-fold spatial cross-validation (every labelled pixel scored once by a model that",
          "never saw it); scores for 3 are on the daksh 2024-03-12 labels only.", "",
          "Confusion matrices: rows = true class (hand label), columns = predicted class.", ""]

    # 1. labelled pixels
    md += ["## Labelled pixels", ""]
    info = {}
    for ds in D.DATASETS:
        counts, groups = label_counts(ds)
        info[ds] = (counts, groups)
        if ds == "external_daksh":
            train = {d: c for d, c in counts.items() if groups[d] == "mathus_naira"}
            test = {d: c for d, c in counts.items() if groups[d] == "daksh"}
        else:
            train, test = counts, counts
        md += [f"### {DATASET_TITLES[ds]}", ""]
        rows = [[d, groups[d], *[f"{v:,}" for v in c], f"{c.sum():,}",
                 "test" if ds == "external_daksh" and groups[d] == "daksh" else "train"]
                for d, c in sorted(counts.items())]
        tot_tr = sum(train.values())
        rows.append(["**training total**", "", *[f"**{v:,}**" for v in tot_tr], f"**{tot_tr.sum():,}**", ""])
        if ds == "external_daksh":
            tot_te = sum(test.values())
            rows.append(["**test total**", "", *[f"**{v:,}**" for v in tot_te], f"**{tot_te.sum():,}**", ""])
        md += [table(rows, ["date", "group", "river", "ice", "snow", "land", "total", "used for"]), ""]
        rows = []
        for t in TASKS:
            if t == "combined":
                continue
            tc = task_counts(t, tot_tr)
            row = [TASK_TITLES[t], ", ".join(f"{k} {v:,}" for k, v in tc.items())]
            if ds == "external_daksh":
                row.append(", ".join(f"{k} {v:,}" for k, v in task_counts(t, sum(test.values())).items()))
            rows.append(row)
        md += ["Pixels per class of each task:", "",
               table(rows, ["task", "training pixels"] + (["test pixels"] if ds == "external_daksh" else [])), ""]

    # 2. scores per model, and model_info.txt
    md += ["## Scores and confusion matrices", ""]
    for ds in D.DATASETS:
        counts, groups = info[ds]
        md += [f"### {DATASET_TITLES[ds]}", ""]
        summary = []
        for t in TASKS:
            tdir = D.task_dir(t, ds)
            D.configure("four" if t == "combined" else t, ds)
            for m, name in D.MODEL_NAMES.items():
                f = tdir / D.MODEL_DIRS[m] / "metrics.txt"
                if not f.exists():
                    continue
                block = first_block(f)
                acc, mf1 = re.search(r"overall accuracy ([\d.]+)\s+macro F1 ([\d.]+)", block).groups()
                summary.append([TASK_TITLES[t], name, acc, mf1])
                md += [f"#### {TASK_TITLES[t]} · {name}", "", f"`{f.parent.relative_to(D.OUTPUT)}/`", "",
                       "```", block, "```", ""]

                if ds == "external_daksh":
                    tr = [d for d in counts if groups[d] == "mathus_naira"]
                    te = [d for d in counts if groups[d] == "daksh"]
                    how = "trained once on all training dates, scored on the test date (no cross-validation)"
                else:
                    tr = te = sorted(counts)
                    how = ("5-fold spatial cross-validation (64-row east-west bands, 12-row buffer), "
                           "then one final model on all labels for the maps")
                hand_tr = sum(counts[d] for d in tr); hand_te = sum(counts[d] for d in te)
                lines = [f"{name} — {TASK_TITLES[t]}", f"dataset: {DATASET_TITLES[ds]}", "",
                         "MODEL"] + ["  " + l for l in MODEL_TEXT[m]]
                if t == "combined":
                    lines += ["  Not trained itself: the binary snow and river models' answers merged",
                              "  (river & no snow = river, river & snow = ice, snow off-river = snow, else land)."]
                lines += ["", "INPUTS", f"  {len(D.CHANNELS)} per pixel: {', '.join(D.CHANNELS)}", "",
                          "DATA", f"  training dates: {', '.join(sorted(tr))}",
                          f"  test dates:     {', '.join(sorted(te))}",
                          "  training pixels: " + ", ".join(f"{k} {v:,}" for k, v in task_counts(t, hand_tr).items())]
                if ds == "external_daksh":
                    lines.append("  test pixels:     " + ", ".join(f"{k} {v:,}" for k, v in task_counts(t, hand_te).items()))
                lines += [f"  evaluation: {how}", "", "SCORES (all dates; per-date scores in metrics.txt)", "",
                          block, "", "FILES",
                          "  metrics.txt       scores, confusion matrix, per date" + (", input importance" if m == "rf" else ""),
                          "  oof.npz           every scored pixel: date, row, col, true, predicted",
                          "  pred_<date>.tif   30 m map of every date (+ .qml colours for QGIS)"]
                if t in ("four", "combined"):
                    lines += ["  scene_mask_*.tif  river/land state per 375 m block; scores in scene_mask_metrics.txt"]
                (f.parent / "model_info.txt").write_text("\n".join(lines) + "\n")
        md += ["Overview (accuracy / macro F1):", "", table(summary, ["task", "model", "accuracy", "macro F1"]), ""]

    # 3. state masks
    md += ["## River/land state per 375 m block", ""]
    rows = []
    for ds in D.DATASETS:
        for t in ("four", "combined"):
            for m, name in D.MODEL_NAMES.items():
                f = D.task_dir(t, ds) / D.MODEL_DIRS[m] / "scene_mask_metrics.txt"
                if f.exists():
                    b = f.read_text().split("\n\n--- ")[0]
                    acc, mf1 = re.search(r"overall accuracy ([\d.]+)\s+macro F1 ([\d.]+)", b).groups()
                    n = sum(int(l.split()[1].replace(",", "")) for l in b.splitlines()
                            if l.startswith("ice_") and len(l.split()) == 5 and "." in l.split()[2])
                    rows.append([D.DATASET_DIRS[ds], TASK_TITLES[t], name, n, acc, mf1])
    md += [table(rows, ["dataset", "from", "model", "blocks", "accuracy", "macro F1"]), "",
           "Full tables with confusion matrices: `scene_mask_metrics.txt` in each model folder.", ""]
    (D.OUTPUT / "RESULTS.md").write_text("\n".join(md))
    print("wrote", D.OUTPUT / "RESULTS.md")


if __name__ == "__main__":
    main()
